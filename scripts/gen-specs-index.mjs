#!/usr/bin/env node
/**
 * gen-specs-index.mjs <scorp-ds dir> <git ref> <output path>
 *
 * Builds the Specs page index from the scorp-ds spec files themselves
 * (docs/specs/*.md at <ref>), so the page never goes stale: vendor:ds writes
 * the JSON and ds:check flags drift when a spec is added, renamed, or its
 * status changes. Each entry links to the rendered markdown on GitHub.
 *
 * Reads the spec's H1, its Status table (Component or Pattern, Layer,
 * Category, Status, Story, Last updated),
 * and the first sentence of its Intent section.
 */
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";

const [dsDir, ref, outPath] = process.argv.slice(2);
if (!dsDir || !ref || !outPath) {
  console.error("usage: gen-specs-index.mjs <scorp-ds dir> <git ref> <output path>");
  process.exit(1);
}

const REPO = "sachahurley/scorp-ds";
const git = (...args) => execFileSync("git", ["-C", dsDir, ...args], { encoding: "utf8" });

const files = git("ls-tree", "--name-only", ref, "docs/specs/")
  .split("\n")
  .filter((f) => f.endsWith(".md"));

// Status table value for a field, without backticks
const field = (md, name) => {
  const m = md.match(new RegExp(`^\\|\\s*${name}\\s*\\|\\s*(.+?)\\s*\\|\\s*$`, "m"));
  return m ? m[1].replace(/`/g, "").trim() : null;
};

// First sentence of the Intent section, markdown stripped
const summary = (md) => {
  const intent = md.split(/^## Intent\s*$/m)[1];
  if (!intent) return null;
  const para = intent
    .split("\n")
    .map((l) => l.trim())
    .find((l) => l && !l.startsWith("<!--") && !l.startsWith("#") && !l.startsWith("|") && l !== "---");
  if (!para) return null;
  const plain = para.replace(/`/g, "").replace(/\*\*/g, "").replace(/\[([^\]]+)\]\([^)]*\)/g, "$1");
  const sentence = plain.match(/^.+?[.!?](\s|$)/);
  return (sentence ? sentence[0] : plain).trim();
};

const GROUPS = [
  { key: "components", title: "Components and primitives" },
  { key: "patterns", title: "Patterns" },
  { key: "meta", title: "Foundation and meta" },
];
const groupFor = (layer, file) => {
  if (file.endsWith("/CHANGELOG.md")) return "meta";
  if (layer === "pattern") return "patterns";
  if (layer === "component" || layer === "primitive") return "components";
  return "meta";
};

const entries = files.map((file) => {
  const md = git("show", `${ref}:${file}`);
  const h1 = (md.match(/^#\s+(.+)$/m) || [])[1] || file;
  const layer = field(md, "Layer");
  return {
    group: groupFor(layer, file),
    name: h1.replace(/^Pattern:\s*/, ""),
    file,
    url: `https://github.com/${REPO}/blob/main/${file}`,
    layer,
    category: field(md, "Category"),
    status: field(md, "Status"),
    story: field(md, "Story"),
    updated: field(md, "Last updated"),
    component: field(md, "Component") || field(md, "Pattern"),
    summary: file.endsWith("/CHANGELOG.md") ? "Every spec creation, rewrite, and fix, newest last." : summary(md),
  };
});

const index = {
  _comment: "Generated by scripts/gen-specs-index.mjs during vendor:ds. Do not edit by hand.",
  source: `https://github.com/${REPO}/tree/main/docs/specs`,
  total: entries.length,
  groups: GROUPS.map(({ key, title }) => ({
    title,
    specs: entries
      .filter((e) => e.group === key)
      .map(({ group, ...rest }) => rest)
      .sort((a, b) => a.name.localeCompare(b.name)),
  })).filter((g) => g.specs.length > 0),
};

writeFileSync(outPath, JSON.stringify(index, null, 2) + "\n");
